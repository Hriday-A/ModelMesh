"""Evaluate the trained router on the held-out test prompts.

    python manage.py evaluate_router

Writes docs/eval/router_eval.md. Uses only recorded benchmark data: for each
strategy it looks up the judge score, cost and latency of the answer it would
have picked. No new API calls.
"""

import json
from datetime import date
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from router import classifier
from router.evaluation import evaluate
from router.models import RouterModel, RoutingSettings
from router.training import BenchmarkError, GOOD_SCORE, bench_path, build_dataset, read_labels, read_prompts, read_results


def pct(x):
    return "—" if x is None else f"{x:.0%}"


class Command(BaseCommand):
    help = "Compare the router against baselines on the test split and write docs/eval/router_eval.md."

    def add_arguments(self, parser):
        parser.add_argument("--output", help="Report path (default docs/eval/router_eval.md).")

    def handle(self, *args, **opts):
        artifact = classifier.load_artifact()
        if artifact is None:
            raise CommandError("No trained router found. Run train_router first.")
        split_path = bench_path("split.json")
        if not split_path.exists():
            raise CommandError("split.json not found. Run train_router first.")
        models = list(RouterModel.objects.filter(enabled=True))
        try:
            rows = build_dataset(read_prompts(), read_labels(), [m.model_id for m in models])
        except BenchmarkError as e:
            raise CommandError(str(e))
        results = read_results()
        test_ids = set(json.loads(split_path.read_text(encoding="utf-8"))["test"])
        test = [r for r in rows if r["id"] in test_ids and all((r["id"], m.model_id) in results for m in models)]
        if not test:
            raise CommandError("No test prompts have labels and results for every model.")
        if artifact.get("good_score", GOOD_SCORE) != GOOD_SCORE:
            raise CommandError(
                f"This router was trained with a good-answer bar of {artifact['good_score']}, but the bar is now "
                f"{GOOD_SCORE}. Run with ROUTER_GOOD_SCORE={artifact['good_score']} or retrain.")
        missing = [m.model_id for m in models if m.model_id not in artifact["models"]]
        if missing:
            raise CommandError(f"The trained router does not know {', '.join(missing)}. Retrain it.")

        report = evaluate(test, models, results, artifact, RoutingSettings.load().confidence_threshold)
        text = self.render(report, models, artifact)
        out = Path(opts["output"]) if opts["output"] else settings.BASE_DIR / "docs" / "eval" / "router_eval.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        self.stdout.write(text)
        self.stdout.write(self.style.SUCCESS(f"Wrote {out}"))

    def render(self, report, models, artifact):
        names = {m.model_id: m.short_name for m in models}
        top = max(models, key=lambda m: m.tier).short_name
        lines = [
            "# Router evaluation",
            "",
            f"Generated by `python manage.py evaluate_router` on {date.today().isoformat()}. "
            f"Router trained on {artifact['n_train']} prompts ({artifact['trained_at']}); "
            f"tested on **{report['n_test']} held-out prompts** it never saw. "
            f"A judge score of {GOOD_SCORE}+ out of 10 counts as a good answer.",
            "",
            f"> Small test set: with {report['n_test']} prompts, one prompt changes a rate by "
            f"{1 / report['n_test']:.0%}. Treat differences of a few points as noise.",
            "",
            "## Strategies compared",
            "",
            f"Quality kept and cost are relative to always using {top}. "
            "Oracle = the cheapest model the judge rated good on each prompt (the best any router could do).",
            "",
            "| Strategy | Avg score | Good answers | Total cost (coins) | Avg latency | Quality kept | Cost vs. always-" + top + " | Matches oracle |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for s in report["strategies"]:
            lines.append(
                f"| {s['name']} | {s['avg_score']:.2f} | {pct(s['good_rate'])} | {s['total_cost']:.4f} | "
                f"{s['avg_latency_ms'] / 1000:.1f} s | {pct(s['quality_kept'])} | {pct(s['cost_share'])} | {pct(s['oracle_match'])} |"
            )

        lines += ["", "## How good are the predictions?", "",
                  f"Category classifier accuracy on the test set: **{pct(report['category_accuracy'])}**.", "",
                  "| Model | Accuracy at 50% | Share of good answers | Brier score (lower is better) |", "|---|---|---|---|"]
        for c in report["classifiers"]:
            lines.append(f"| {names[c['model_id']]} | {pct(c['accuracy'])} | {pct(c['base_rate'])} | {c['brier']:.3f} |")
        lines += ["", "Calibration: when the classifier says X%, how often was the answer actually good?", "",
                  "| Model | Predicted range | Prompts | Avg predicted | Actually good |", "|---|---|---|---|---|"]
        for c in report["classifiers"]:
            for b in c["calibration"]:
                lines.append(f"| {names[c['model_id']]} | {b['bin']} | {b['n']} | {pct(b['predicted'])} | {pct(b['actual'])} |")

        lines += ["", "## Cost vs. quality as the cost weight changes", "",
                  "Quality weight 1, speed weight 0. Higher cost weight = the router saves more and risks more.", "",
                  "| Cost weight | Avg score | Total cost (coins) | Picks |", "|---|---|---|---|"]
        for c in report["curve"]:
            share = ", ".join(f"{k} {v}" for k, v in c["share"].items())
            lines.append(f"| {c['cost_weight']} | {c['avg_score']:.2f} | {c['total_cost']:.4f} | {share} |")

        lines += ["", "## Test decisions (Balanced priority)", "",
                  "Expected = oracle pick. Score and latency are the recorded values for the router's pick.", "",
                  "| # | Prompt | Category (predicted) | Expected | Router picked | Judge score | Latency |", "|---|---|---|---|---|---|---|"]
        for i, s in enumerate(report["samples"], start=1):
            prompt = s["prompt"].replace("|", "\\|").replace("\n", " ")
            prompt = prompt[:70] + ("…" if len(prompt) > 70 else "")
            lines.append(
                f"| {i} | {prompt} | {s['category']} ({s['predicted_category']}) | {names[s['expected']]} | "
                f"{names[s['actual']]} | {s['score']} | {s['latency_ms'] / 1000:.1f} s |"
            )

        lines += ["", "## Router overhead", "",
                  f"Median time to embed one prompt and score the models: **{report['embed_ms']:.0f} ms** "
                  "(CPU, after the embedder is loaded). This is added to every request before the LLM call.", ""]
        return "\n".join(lines)
